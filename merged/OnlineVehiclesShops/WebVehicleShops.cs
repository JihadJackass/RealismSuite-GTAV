	private static bool RoadsideOffset(Vector3 nodePos, float nodeHeading, int lanes, int properties, float modelWidth, out float offsetToKerb, bool allowReject = true)
	{
		offsetToKerb = 0f;
		if (((uint)properties & 0x400u) != 0)
		{
			return false;
		}
		if (allowReject)
		{
			if (((uint)properties & 0x80u) != 0)
			{
				return false;
			}
			if (((uint)properties & 0x100u) != 0)
			{
				return false;
			}
			if (((uint)properties & 0x200u) != 0)
			{
				return false;
			}
		}
		OutputArgument outputArgument = new OutputArgument();
		OutputArgument outputArgument2 = new OutputArgument();
		OutputArgument outputArgument3 = new OutputArgument();
		OutputArgument outputArgument4 = new OutputArgument();
		OutputArgument outputArgument5 = new OutputArgument();
		if (!Function.Call<bool>(Hash.GET_CLOSEST_ROAD, nodePos.X, nodePos.Y, nodePos.Z, 1f, 1, outputArgument, outputArgument2, outputArgument3, outputArgument4, outputArgument5, false))
		{
			return false;
		}
		int result = outputArgument3.GetResult<int>();
		int result2 = outputArgument4.GetResult<int>();
		float result3 = outputArgument5.GetResult<float>();
		if (result + result2 != lanes)
		{
			if (allowReject)
			{
				return false;
			}
			offsetToKerb = 0f;
			return true;
		}
		int num = ((nodeHeading <= 90f || nodeHeading > 270f) ? result : result2);
		if (num == 0)
		{
			if (allowReject)
			{
				return false;
			}
			offsetToKerb = 0f;
			return true;
		}
		bool flag = lanes == num;
		if (result3 < 0f)
		{
			offsetToKerb = 0f;
			return true;
		}
		offsetToKerb = (flag ? (4.2f * ((float)num * 0.5f)) : (4.2f * (float)num));
		if (flag)
		{
			if (num > 2)
			{
				offsetToKerb += (float)(num - 2) * 1f;
			}
		}
		else if (num > 1)
		{
			offsetToKerb += (float)(num - 1) * 1f;
		}
		if (((uint)properties & 0x40u) != 0)
		{
			offsetToKerb += 0.95f * result3;
		}
		if (((uint)properties & 4u) != 0 || ((uint)properties & 8u) != 0)
		{
			offsetToKerb -= 0.5f;
		}
		if (((uint)properties & 0x20u) != 0 && (properties & 4) == 0 && (properties & 8) == 0)
		{
			offsetToKerb -= 1f;
		}
		offsetToKerb += -2.1f;
		if (modelWidth > 1.8f)
		{
			offsetToKerb += (modelWidth - 1.8f) * -0.5f;
		}
		if (offsetToKerb < 0f)
		{
			offsetToKerb = 0f;
		}
		return true;
	}

